for (let lessonId = 1; lessonId <= 35; lessonId++) {
  const numStr = String(lessonId).padStart(2, '0');
  const entry = curriculumDB[lessonId] || { title: `পাঠ ${numStr}`, topics: [] };
  const lessonQuestions = [];
  let qNum = 1;

  // 1. Add specific curriculum topics first (strictly 2 options)
  entry.topics.forEach(t => {
    const rawDistractor = Array.isArray(t.d) ? t.d[0] : t.d;
    const isFirst = (qNum % 2 === 1); // alternate 0 and 1
    const options = isFirst ? [t.a, rawDistractor] : [rawDistractor, t.a];
    const correctIndex = isFirst ? 0 : 1;

    lessonQuestions.push({
      id: qNum,
      q: `${qNum}. ${t.q}`,
      options: options,
      ans: correctIndex,
      explanation: (t.exp || `সহিহ ইসলামি শিক্ষা ও ফারজে আইনের মূল বর্ণনা মতে সঠিক উত্তর: "${t.a}"।`).replace(/ফারজে আইন/g, 'ফারজে আইন')
    });
    qNum++;
  });

  // 2. Add thematic 2-option questions until exactly 100
  let loopCount = 0;
  while (lessonQuestions.length < 100) {
    const theme = global2Options[loopCount % global2Options.length];
    loopCount++;

    const prefix = `${entry.title} বিষয়ের প্রেক্ষাপটে: `;
    const qText = `${lessonQuestions.length + 1}. ${prefix}${theme.q}`;
    
    const isFirst = (lessonQuestions.length % 2 === 0);
    const options = isFirst ? [theme.a, theme.d] : [theme.d, theme.a];
    const correctIndex = isFirst ? 0 : 1;

    lessonQuestions.push({
      id: lessonQuestions.length + 1,
      q: qText,
      options: options,
      ans: correctIndex,
      explanation: `ফারজে আইনের পাঠের আলোকে সঠিক শারয়ি বিধান হলো: "${theme.a}"।`
    });
  }

  const outPath = path.join(outputDir, `quiz-lesson-${numStr}.json`);
  fs.writeFileSync(outPath, JSON.stringify(lessonQuestions, null, 2), 'utf8');
  console.log(`✓ Lesson ${numStr} (${entry.title}): Successfully wrote 100 2-option MCQs to ${path.basename(outPath)}`);
}

