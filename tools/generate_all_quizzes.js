  fs.writeFileSync(outPath, JSON.stringify(lessonQuestions, null, 2), 'utf8');
  console.log(`✓ Lesson ${numStr} (${entry.title}): Successfully wrote 100 MCQs to ${path.basename(outPath)}`);
